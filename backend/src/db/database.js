import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { DatabaseSync } from "node:sqlite";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const dataDir = path.resolve(__dirname, "../../data");
const dbPath = path.join(dataDir, "family-calendar.db");

if (!fs.existsSync(dataDir)) {
  fs.mkdirSync(dataDir, { recursive: true });
}

export const db = new DatabaseSync(dbPath);
db.exec("PRAGMA foreign_keys = ON");

export function initDatabase() {
  db.exec(`
    CREATE TABLE IF NOT EXISTS USERS (
      ID INTEGER PRIMARY KEY AUTOINCREMENT,
      EMAIL TEXT NOT NULL UNIQUE,
      PASSWORD TEXT NOT NULL,
      NAME TEXT NOT NULL,
      ROLE TEXT NOT NULL CHECK (ROLE IN ('ADMIN', 'MEMBER')),
      STATUS TEXT NOT NULL CHECK (STATUS IN ('PENDING', 'APPROVED', 'REJECTED')),
      CREATED_AT TEXT NOT NULL
    );

    CREATE TABLE IF NOT EXISTS GROUPS (
      ID INTEGER PRIMARY KEY AUTOINCREMENT,
      NAME TEXT NOT NULL UNIQUE,
      COLOR TEXT NOT NULL,
      CREATED_BY INTEGER NOT NULL,
      CREATED_AT TEXT NOT NULL,
      FOREIGN KEY (CREATED_BY) REFERENCES USERS(ID)
    );

    CREATE TABLE IF NOT EXISTS GROUP_MEMBERS (
      GROUP_ID INTEGER NOT NULL,
      USER_ID INTEGER NOT NULL,
      CREATED_AT TEXT NOT NULL,
      PRIMARY KEY (GROUP_ID, USER_ID),
      FOREIGN KEY (GROUP_ID) REFERENCES GROUPS(ID) ON DELETE CASCADE,
      FOREIGN KEY (USER_ID) REFERENCES USERS(ID) ON DELETE CASCADE
    );

    CREATE TABLE IF NOT EXISTS EVENTS (
      ID INTEGER PRIMARY KEY AUTOINCREMENT,
      TITLE TEXT NOT NULL,
      DESCRIPTION TEXT,
      EVENT_DATE TEXT NOT NULL,
      START_TIME TEXT,
      END_TIME TEXT,
      COLOR TEXT NOT NULL,
      VISIBILITY TEXT NOT NULL CHECK (VISIBILITY IN ('ALL', 'GROUP')),
      CREATED_BY INTEGER NOT NULL,
      CREATED_AT TEXT NOT NULL,
      UPDATED_AT TEXT NOT NULL,
      FOREIGN KEY (CREATED_BY) REFERENCES USERS(ID)
    );

    CREATE TABLE IF NOT EXISTS EVENT_GROUPS (
      EVENT_ID INTEGER NOT NULL,
      GROUP_ID INTEGER NOT NULL,
      PRIMARY KEY (EVENT_ID, GROUP_ID),
      FOREIGN KEY (EVENT_ID) REFERENCES EVENTS(ID) ON DELETE CASCADE,
      FOREIGN KEY (GROUP_ID) REFERENCES GROUPS(ID) ON DELETE CASCADE
    );

    CREATE TABLE IF NOT EXISTS TODOS (
      ID INTEGER PRIMARY KEY AUTOINCREMENT,
      TITLE TEXT NOT NULL,
      DUE_DATE TEXT NOT NULL,
      COMPLETED INTEGER NOT NULL DEFAULT 0,
      COLOR TEXT NOT NULL,
      VISIBILITY TEXT NOT NULL CHECK (VISIBILITY IN ('ALL', 'GROUP')),
      CREATED_BY INTEGER NOT NULL,
      CREATED_AT TEXT NOT NULL,
      UPDATED_AT TEXT NOT NULL,
      FOREIGN KEY (CREATED_BY) REFERENCES USERS(ID)
    );

    CREATE TABLE IF NOT EXISTS TODO_GROUPS (
      TODO_ID INTEGER NOT NULL,
      GROUP_ID INTEGER NOT NULL,
      PRIMARY KEY (TODO_ID, GROUP_ID),
      FOREIGN KEY (TODO_ID) REFERENCES TODOS(ID) ON DELETE CASCADE,
      FOREIGN KEY (GROUP_ID) REFERENCES GROUPS(ID) ON DELETE CASCADE
    );

    CREATE TABLE IF NOT EXISTS NOTIFICATION_READS (
      USER_ID INTEGER NOT NULL,
      EVENT_ID INTEGER NOT NULL,
      READ_AT TEXT NOT NULL,
      PRIMARY KEY (USER_ID, EVENT_ID),
      FOREIGN KEY (USER_ID) REFERENCES USERS(ID) ON DELETE CASCADE,
      FOREIGN KEY (EVENT_ID) REFERENCES EVENTS(ID) ON DELETE CASCADE
    );

    CREATE TABLE IF NOT EXISTS FAMILIES (
      ID INTEGER PRIMARY KEY AUTOINCREMENT,
      NAME TEXT NOT NULL UNIQUE,
      COLOR TEXT NOT NULL,
      CREATED_AT TEXT NOT NULL
    );

    CREATE TABLE IF NOT EXISTS PUSH_SUBSCRIPTIONS (
      USER_ID INTEGER NOT NULL,
      ENDPOINT TEXT NOT NULL UNIQUE,
      P256DH TEXT NOT NULL,
      AUTH TEXT NOT NULL,
      CREATED_AT TEXT NOT NULL,
      FOREIGN KEY (USER_ID) REFERENCES USERS(ID) ON DELETE CASCADE
    );

    CREATE TABLE IF NOT EXISTS GAME_SCORES (
      ID INTEGER PRIMARY KEY AUTOINCREMENT,
      USER_ID INTEGER NOT NULL,
      FAMILY_ID INTEGER,
      SCORE INTEGER NOT NULL,
      CREATED_AT TEXT NOT NULL,
      FOREIGN KEY (USER_ID) REFERENCES USERS(ID) ON DELETE CASCADE
    );
  `);

  addColumnIfMissing("EVENTS", "REMIND_MINUTES", "INTEGER NOT NULL DEFAULT -1");
  addColumnIfMissing("USERS", "FAMILY_ID", "INTEGER");
  addColumnIfMissing("USERS", "IS_FAMILY_ADMIN", "INTEGER NOT NULL DEFAULT 0");
  addColumnIfMissing("EVENTS", "FAMILY_ID", "INTEGER");
  addColumnIfMissing("FAMILIES", "BACKGROUND", "TEXT");
  addColumnIfMissing("FAMILIES", "IS_CLAN", "INTEGER NOT NULL DEFAULT 0");
  addColumnIfMissing("EVENTS", "END_DATE", "TEXT");
  addColumnIfMissing("EVENTS", "IS_FAMILY_EVENT", "INTEGER NOT NULL DEFAULT 0");
  db.exec(`UPDATE EVENTS SET END_DATE = EVENT_DATE WHERE END_DATE IS NULL OR END_DATE = ''`);

  db.exec(`
    UPDATE EVENTS
    SET FAMILY_ID = (
      SELECT u.FAMILY_ID FROM USERS u WHERE u.ID = EVENTS.CREATED_BY
    )
    WHERE FAMILY_ID IS NULL
  `);
}

function addColumnIfMissing(table, column, definition) {
  const columns = db.prepare(`PRAGMA table_info(${table})`).all();
  if (!columns.some((item) => item.name === column)) {
    db.exec(`ALTER TABLE ${table} ADD COLUMN ${column} ${definition}`);
  }
}
